#!/usr/bin/env python3
"""Draws the site background from real star positions.

The field is the Winter Hexagon region around Orion (Betelgeuse, Rigel, the
belt and sword, Sirius, Procyon, Pollux, Aldebaran, and the Pleiades), as seen
facing south on a January evening: north up, east to the left.

Star data: d3-celestial (BSD-3-Clause, (c) Olaf Frohn), whose star files are
built from the Hipparcos catalogue. Download it, then point this script at the
stars file:

    npm pack d3-celestial@0.7.35 && tar -xzf d3-celestial-0.7.35.tgz
    python3 scripts/build-sky.py package/data/stars.8.json public/sky/winter-hexagon.svg
"""
import json
import math
import sys

# Field centre and size, in degrees. RA increases to the east (left on screen).
RA0, DEC0 = 92.0, 6.0
HALF_WIDTH_DEG = 40.0
VIEW_W, VIEW_H = 1600, 1067  # 3:2; the page scales it to cover the screen
MAG_LIMIT = 7.2  # a little fainter than a dark rural sky, for texture
TWINKLE_COUNT = 22  # the brightest stars twinkle

# Named stars to check the framing (Hipparcos numbers).
LANDMARKS = {27989: "Betelgeuse", 24436: "Rigel", 26311: "Alnilam", 32349: "Sirius",
             37279: "Procyon", 37826: "Pollux", 36850: "Castor", 21421: "Aldebaran", 17702: "Alcyone (Pleiades)"}

SCALE = (VIEW_W / 2) / math.tan(math.radians(HALF_WIDTH_DEG))


def project(ra_deg, dec_deg):
    """Gnomonic (camera-like) projection centred on RA0/DEC0, east to the left."""
    ra, dec = math.radians(ra_deg), math.radians(dec_deg)
    ra0, dec0 = math.radians(RA0), math.radians(DEC0)
    cos_c = math.sin(dec0) * math.sin(dec) + math.cos(dec0) * math.cos(dec) * math.cos(ra - ra0)
    if cos_c <= 0.2:
        return None  # behind or far outside the field
    xi = math.cos(dec) * math.sin(ra - ra0) / cos_c
    eta = (math.cos(dec0) * math.sin(dec) - math.sin(dec0) * math.cos(dec) * math.cos(ra - ra0)) / cos_c
    return VIEW_W / 2 - xi * SCALE, VIEW_H / 2 - eta * SCALE


def lerp(a, b, t):
    return a + (b - a) * t


# B-V colour index to a gentle, desaturated star tint (natural, never neon).
STOPS = [(-0.3, (170, 191, 255)), (0.0, (202, 215, 255)), (0.4, (238, 241, 248)),
         (0.8, (255, 240, 222)), (1.2, (255, 214, 170)), (1.8, (255, 190, 130))]


def bv_color(bv):
    bv = max(STOPS[0][0], min(STOPS[-1][0], bv))
    for (b0, c0), (b1, c1) in zip(STOPS, STOPS[1:]):
        if bv <= b1:
            t = (bv - b0) / (b1 - b0)
            return "#%02x%02x%02x" % tuple(round(lerp(x, y, t)) for x, y in zip(c0, c1))
    return "#eef1f8"


def radius(mag):
    return max(0.5, 3.6 - 0.42 * (mag + 1.5))


def opacity(mag):
    return max(0.35, min(1.0, 1.1 - 0.1 * mag))


def main(src, out):
    features = json.load(open(src))["features"]
    stars = []
    for f in features:
        mag = f["properties"]["mag"]
        if mag > MAG_LIMIT:
            continue
        lon, dec = f["geometry"]["coordinates"]
        ra = lon % 360
        p = project(ra, dec)
        if not p:
            continue
        x, y = p
        if -10 <= x <= VIEW_W + 10 and -10 <= y <= VIEW_H + 10:
            try:
                bv = float(f["properties"].get("bv") or 0.6)
            except ValueError:
                bv = 0.6
            stars.append((mag, x, y, bv, f.get("id")))

    stars.sort(key=lambda s: -s[0])  # faint first, so bright stars draw on top
    bright = sorted(stars, key=lambda s: s[0])[:TWINKLE_COUNT]
    twinkle_ids = {id(s) for s in bright}

    body = []
    for i, s in enumerate(stars):
        mag, x, y, bv, hip = s
        color = bv_color(bv)
        r = radius(mag)
        if mag < 2.6:  # soft halo on the bright stars, so the constellations read
            body.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r * 3:.1f}" fill="{color}" opacity=".13"/>')
        cls = ""
        if id(s) in twinkle_ids:
            n = len([b for b in body if 'class="tw"' in b])
            dur = 3.5 + (n * 7 % 11) * 0.5
            cls = f' class="tw" style="animation-duration:{dur:.1f}s;animation-delay:-{(n * 1.7) % dur:.1f}s"'
        body.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.2f}" fill="{color}" opacity="{opacity(mag):.2f}"{cls}/>')

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW_W} {VIEW_H}" preserveAspectRatio="xMidYMid slice">
<!-- The Winter Hexagon around Orion, from the Hipparcos catalogue via d3-celestial
     (BSD-3-Clause, (c) Olaf Frohn). Generated by scripts/build-sky.py. {len(stars)} stars to magnitude {MAG_LIMIT}. -->
<style>
.tw {{ animation: tw ease-in-out infinite; transform-box: fill-box; transform-origin: center; }}
@keyframes tw {{ 0%,100% {{ opacity: .55; transform: scale(.85); }} 50% {{ opacity: 1; transform: scale(1.2); }} }}
@media (prefers-reduced-motion: reduce) {{ .tw {{ animation: none; }} }}
</style>
<rect width="100%" height="100%" fill="#000"/>
{chr(10).join(body)}
</svg>
"""
    open(out, "w").write(svg)

    by_hip = {s[4]: s for s in stars}
    print(f"{len(stars)} stars, {len(svg) // 1024} KB")
    for hip, name in LANDMARKS.items():
        s = by_hip.get(hip)
        print(f"  {name:20s}", f"x={s[1]:.0f} y={s[2]:.0f} mag={s[0]}" if s else "outside field")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
